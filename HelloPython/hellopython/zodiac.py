"""Определение знака зодиака."""

def zodiac_sign(day, month):
    if (month == 1 and day <= 19) or (month == 12 and day >= 22):
        return "Козерог"
    signs = [
        ((1, 20), "Водолей"), ((2, 19), "Рыбы"), ((3, 21), "Овен"),
        ((4, 20), "Телец"), ((5, 21), "Близнецы"), ((6, 21), "Рак"),
        ((7, 23), "Лев"), ((8, 23), "Дева"), ((9, 23), "Весы"),
        ((10, 23), "Скорпион"), ((11, 22), "Стрелец"),
    ]
    for (m, d), sign in signs:
        if (month, day) < (m, d):
            return sign
    return "Стрелец"
